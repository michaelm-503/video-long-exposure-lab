def _render_demo_gallery() -> VideoSelection | None:
    """Render demo source options and return a selected local/remote video."""
    st.subheader("Demo Gallery")
    st.write(
        "Choose a hosted demo clip, use a local sample file, or paste a direct video URL. "
        "Demo clips are stored as GitHub Release assets so the repo stays small."
    )
    card_selection = _render_demo_source_cards()
    if card_selection is not None:
        return card_selection
    st.markdown(f"[Open demo media release]({DEMO_RELEASE_URL})")

    gallery_columns = st.columns(2)
    local_files = _sample_video_files()
    with gallery_columns[0]:
        st.markdown("**Local sample video**")
        if local_files:
            selected_local = st.selectbox(
                "sample_data videos",
                options=local_files,
                format_func=lambda path: path.name,
            )
            if st.button("Use local sample", type="primary"):
                _cleanup_session_temp_files()
                return _load_local_video(selected_local)
        else:
            st.info("Place .mp4, .mov, or .m4v files in sample_data/ to use them here.")

    with gallery_columns[1]:
        st.markdown("**Direct video URL**")
        direct_url = st.text_input(
            "Direct .mp4/.mov/.m4v URL",
            value="",
            placeholder="https://example.com/sample.mp4",
        )
        if st.button("Load video URL", type="primary"):
            _cleanup_session_temp_files()
            return _download_video_url(direct_url)

    return st.session_state.get("demo_video_selection")


def _render_video_input() -> VideoSelection | None:
    """Render upload/demo input choices and return the active video."""
    input_mode = st.radio(
        "Select video source",
        ["Upload video", "Demo gallery"],
        horizontal=True,
    )

    if input_mode == "Demo gallery":
        selection = _render_demo_gallery()
        if isinstance(selection, VideoSelection):
            st.session_state.demo_video_selection = selection
        return st.session_state.get("demo_video_selection")

    uploaded_file = st.file_uploader(
        "Upload a short video",
        type=["mov", "mp4", "m4v"],
        accept_multiple_files=False,
        help="Use clips up to 25 MB. For Streamlit Cloud, 2K or smaller video is strongly recommended.",
    )
    if uploaded_file is None:
        return None

    uploaded_bytes = uploaded_file.getvalue()
    if len(uploaded_bytes) > MAX_UPLOAD_VIDEO_BYTES:
        raise ValueError("Upload a video that is 25 MB or smaller for the Streamlit demo.")

    suffix = Path(uploaded_file.name).suffix
    upload_signature = ("upload", uploaded_file.name, len(uploaded_bytes))
    if st.session_state.get("active_upload_signature") != upload_signature:
        _cleanup_session_temp_files()
        st.session_state.active_upload_signature = upload_signature

    video_path = save_uploaded_video_to_temp(uploaded_bytes, suffix, _session_temp_dir())
    return VideoSelection(
        name=uploaded_file.name,
        suffix=suffix,
        video_bytes=uploaded_bytes,
        video_path=video_path,
        signature=upload_signature,
        cleanup_path=True,
    )



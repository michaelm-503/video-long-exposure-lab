def _encode_image(image_bgr: np.ndarray, extension: str) -> bytes:
    """Encode a BGR image for downloads."""
    encode_params = [cv2.IMWRITE_JPEG_QUALITY, 95] if extension == ".jpg" else []
    ok, encoded = cv2.imencode(extension, image_bgr, encode_params)
    if not ok:
        raise ValueError(f"Could not encode image as {extension}")
    return encoded.tobytes()


def _encode_gray_png(mask: np.ndarray) -> bytes:
    """Encode a 2D mask as PNG bytes."""
    ok, encoded = cv2.imencode(".png", np.clip(mask, 0, 255).astype(np.uint8))
    if not ok:
        raise ValueError("Could not encode alpha mask as PNG")
    return encoded.tobytes()


def _save_output_images(image_bgr: np.ndarray) -> tuple[Path, Path]:
    """Save PNG and JPEG outputs locally for portfolio/demo runs."""
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    png_path = OUTPUT_DIR / "long_exposure.png"
    jpg_path = OUTPUT_DIR / "long_exposure.jpg"
    cv2.imwrite(str(png_path), image_bgr)
    cv2.imwrite(str(jpg_path), image_bgr, [cv2.IMWRITE_JPEG_QUALITY, 95])
    return png_path, jpg_path


def _render_video(
    video_bytes: bytes,
    *,
    suffix: str,
    video_width: int,
) -> None:
    """Render video at its intrinsic width or shrink to fit."""
    encoded_video = base64.b64encode(video_bytes).decode("ascii")
    mime_type = VIDEO_MIME_TYPES.get(suffix.lower(), "video/mp4")
    max_width = min(PREVIEW_RESIZE_WIDTH, max(1, video_width))
    st.markdown(
        f"""
        <video class="content-sized-video" controls preload="metadata"
            style="width: min({max_width}px, 100%);">
            <source src="data:{mime_type};base64,{encoded_video}" type="{mime_type}">
        </video>
        """,
        unsafe_allow_html=True,
    )


def _sample_video_files() -> list[Path]:
    """Return local demo videos that are intentionally untracked by git."""
    if not SAMPLE_DATA_DIR.exists():
        return []

    return sorted(
        path
        for path in SAMPLE_DATA_DIR.iterdir()
        if path.is_file() and path.suffix.lower() in LOCAL_SAMPLE_SUFFIXES
    )


def _load_local_video(path: Path) -> VideoSelection:
    """Build a video selection from a local sample file."""
    stat = path.stat()
    return VideoSelection(
        name=path.name,
        suffix=path.suffix,
        video_bytes=None,
        video_path=path,
        signature=("local", str(path.resolve()), stat.st_size, stat.st_mtime_ns),
        cleanup_path=False,
    )


def _download_video_url(url: str) -> VideoSelection:
    """Download a direct remote video URL to a temporary file."""
    parsed = urlparse(url.strip())
    if parsed.scheme not in {"http", "https"} or not parsed.netloc:
        raise ValueError("Enter a valid http or https video URL.")

    suffix = Path(parsed.path).suffix.lower()
    request = Request(
        url,
        headers={"User-Agent": "video-long-exposure-lab/1.0"},
    )
    try:
        with urlopen(request, timeout=45) as response:
            content_type = response.headers.get("Content-Type", "").lower()
            content_length = response.headers.get("Content-Length")
            content_length_bytes = (
                int(content_length) if content_length and content_length.isdigit() else 0
            )
            if content_length_bytes > MAX_REMOTE_VIDEO_BYTES:
                raise ValueError("Remote video is larger than the demo download limit.")
            if not content_type.startswith("video/") and suffix not in LOCAL_SAMPLE_SUFFIXES:
                raise ValueError(
                    "That link did not look like a direct video file. Open the source page, "
                    "copy a direct .mp4/.mov/.m4v video URL, or place the clip in sample_data/."
                )

            chunks: list[bytes] = []
            bytes_read = 0
            while True:
                chunk = response.read(1024 * 1024)
                if not chunk:
                    break
                bytes_read += len(chunk)
                if bytes_read > MAX_REMOTE_VIDEO_BYTES:
                    raise ValueError("Remote video is larger than the demo download limit.")
                chunks.append(chunk)
    except HTTPError as error:
        raise ValueError(f"Could not download the video URL: HTTP {error.code}.") from error
    except URLError as error:
        raise ValueError(f"Could not download the video URL: {error.reason}.") from error
    except TimeoutError as error:
        raise ValueError("Could not download the video URL before the connection timed out.") from error
    except OSError as error:
        raise ValueError(f"Could not download the video URL: {error}.") from error

    video_bytes = b"".join(chunks)
    if not video_bytes:
        raise ValueError("No video bytes could be downloaded from that URL.")

    if suffix not in LOCAL_SAMPLE_SUFFIXES:
        if "quicktime" in content_type:
            suffix = ".mov"
        elif "mp4" in content_type:
            suffix = ".mp4"
        else:
            suffix = ".mp4"

    video_path = _write_session_temp_video(video_bytes, suffix)

    return VideoSelection(
        name=Path(parsed.path).name or "remote-demo-video",
        suffix=suffix,
        video_bytes=None,
        video_path=video_path,
        signature=("remote", url, len(video_bytes)),
        cleanup_path=False,
    )


def _demo_title_html(source: dict[str, str]) -> str:
    """Return linked title markup for a demo source."""
    title = source.get("title") or source["filename"]
    source_url = source.get("source_url", "")
